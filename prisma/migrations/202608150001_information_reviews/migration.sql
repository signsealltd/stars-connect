  INDEX `InformationReviewRequest_studentId_createdAt_idx` (`studentId`, `createdAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `InformationReviewRequest_organisationId_fkey` FOREIGN KEY (`organisationId`) REFERENCES `Organisation` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
