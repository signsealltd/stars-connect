  `id` CHAR(36) NOT NULL,
  `organisationId` CHAR(36) NOT NULL,
  `studentId` CHAR(36) NOT NULL,
  `tokenHash` CHAR(64) NOT NULL,
  `status` ENUM('DRAFT','SENT','OPENED','IN_PROGRESS','SUBMITTED','UNDER_REVIEW','PARTIALLY_APPROVED','COMPLETED','EXPIRED','REVOKED') NOT NULL DEFAULT 'DRAFT',
  `source` ENUM('ONLINE','PAPER','ASSISTED') NOT NULL DEFAULT 'ONLINE',
  `verifyDateOfBirth` BOOLEAN NOT NULL DEFAULT false,
  `verificationFailures` INTEGER NOT NULL DEFAULT 0,
  `lockedUntil` DATETIME(3) NULL,
  `expiresAt` DATETIME(3) NOT NULL,
  `openedAt` DATETIME(3) NULL,
  `submittedAt` DATETIME(3) NULL,
  `completedAt` DATETIME(3) NULL,
  `revokedAt` DATETIME(3) NULL,
  `lastSavedAt` DATETIME(3) NULL,
  `sentAt` DATETIME(3) NULL,
